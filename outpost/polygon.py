"""Import a Polygon package (the zip Polygon builds under *Packages*).

Takes either a full package (Linux/Windows, tests already generated) or a
standard one (manual tests + generators): missing inputs are generated by
running the package's generators with each test's ``cmd``, missing answers by
running the **main** solution — only the main one, never a ``wa_*``/``tl_*``
solution, which is how a bad answer file gets into a package.

The problem lands in ``<data>/problems/<short-name>/``::

    problem.xml            the package's, for reference
    tests/01, 01.a, …      inputs and answers
    check, interactor      compiled testlib checker / interactor
    statements/<lang>/     images and problem.pdf, per language

and its row in ``problems`` is created or updated in place (same id, so contests
that already use the problem keep working after a re-import).
"""

from __future__ import annotations

import functools
import json
import os
import shlex
import shutil
import subprocess
import tempfile
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path
from typing import Callable

from . import db, languages, latex
from .config import Settings
from .judge import ACCEPTED, Judge, ProblemSpec
from .sandbox import Sandbox, build_launcher, jail_available, network_isolation_available

Log = Callable[[str], None]

STATEMENT_SECTIONS = ("legend", "input", "output", "interaction", "notes", "scoring", "tutorial")
IMAGE_EXT = {".png", ".jpg", ".jpeg", ".gif", ".svg", ".bmp", ".webp"}


class ImportError_(Exception):
    pass


def pdf_problem(path: Path) -> str | None:
    """Why ``path`` is not a PDF that opens (it doesn't parse, or has no pages); None if it is fine."""
    from pypdf import PdfReader
    try:
        reader = PdfReader(path)
        for page in reader.pages:
            page.mediabox
        pages = len(reader.pages)
    except Exception as e:  # pypdf raises many kinds on damaged files
        return f"it doesn't parse ({type(e).__name__}: {e})"
    return None if pages else "it has no pages"


@functools.lru_cache(maxsize=4096)
def _pdf_opens(path: str, mtime_ns: int, size: int) -> bool:
    return pdf_problem(Path(path)) is None


def pdf_opens(path: Path) -> bool:
    """Whether ``path`` is a PDF that opens; parsed once per file version, then cached."""
    try:
        st = path.stat()
    except OSError:
        return False
    return path.is_file() and _pdf_opens(str(path), st.st_mtime_ns, st.st_size)


def drop_broken_pdf(path: Path, shown_as: str, log: Log) -> bool:
    """Delete ``path`` if it is a PDF that doesn't open, saying so in the log; True if it is kept."""
    why = pdf_problem(path)
    if why is None:
        return True
    log(f"WARNING statement PDF {shown_as} dropped: {why}")
    path.unlink(missing_ok=True)
    return False


def safe_extract(zip_path: Path, dest: Path) -> None:
    dest = dest.resolve()
    with zipfile.ZipFile(zip_path) as zf:
        for member in zf.infolist():
            target = (dest / member.filename).resolve()
            if not target.is_relative_to(dest):
                raise ImportError_(f"unsafe path in archive: {member.filename}")
        zf.extractall(dest)


def find_root(extracted: Path) -> Path:
    if (extracted / "problem.xml").exists():
        return extracted
    hits = sorted(extracted.rglob("problem.xml"), key=lambda p: len(p.parts))
    if not hits:
        raise ImportError_("no problem.xml in the archive — is this a Polygon package?")
    return hits[0].parent


def compile_cpp(src: Path, out: Path, include: list[Path], log: Log) -> None:
    argv = ["g++", "-std=gnu++20", "-O2", "-pipe"]
    for inc in include:
        argv += ["-I", str(inc)]
    argv += ["-o", str(out), str(src)]
    res = subprocess.run(argv, capture_output=True, text=True, timeout=180)
    if res.returncode != 0:
        raise ImportError_(f"compiling {src.name} failed:\n{res.stderr[-3000:]}")
    log(f"compiled {src.name}")


def parse(root: Path) -> dict:
    """Read the parts of problem.xml we use into plain data."""
    xml = ET.parse(root / "problem.xml").getroot()
    names = {n.get("language"): n.get("value") for n in xml.findall("./names/name")}
    judging = xml.find("judging")
    testset = None
    if judging is not None:
        testset = judging.find("testset[@name='tests']")
        if testset is None:
            testset = judging.find("testset")
    if testset is None:
        raise ImportError_("problem.xml has no testset")

    def text(tag: str, default: str = "") -> str:
        el = testset.find(tag)
        return el.text.strip() if el is not None and el.text else default

    tests = []
    for n, t in enumerate(testset.findall("./tests/test"), 1):
        tests.append({
            "index": n,
            "method": t.get("method", "manual"),
            "cmd": t.get("cmd"),
            "from_file": t.get("from-file"),
            "sample": t.get("sample") == "true",
            "group": t.get("group", ""),
            "points": float(t.get("points")) if t.get("points") else 0.0,
        })
    groups = []
    for g in testset.findall("./groups/group"):
        groups.append({
            "name": g.get("name"),
            "points": float(g.get("points") or 0),
            "policy": g.get("points-policy", "complete-group"),
            "dependencies": [d.get("group") for d in g.findall("./dependencies/dependency")],
        })

    def source_of(path: str) -> tuple[Path, str] | None:
        el = xml.find(path)
        if el is None:
            return None
        src = el.find("source")
        if src is None:
            return None
        return root / src.get("path"), src.get("type", "")

    main = None
    for sol in xml.findall("./assets/solutions/solution"):
        if sol.get("tag") == "main" and sol.find("source") is not None:
            s = sol.find("source")
            main = (root / s.get("path"), s.get("type", ""))
    executables = []
    for ex in xml.findall("./files/executables/executable"):
        s = ex.find("source")
        if s is not None:
            executables.append((root / s.get("path"), s.get("type", "")))
    validator = None
    vsrc = xml.find("./assets/validators/validator/source")
    if vsrc is not None:
        validator = (root / vsrc.get("path"), vsrc.get("type", ""))
    pdfs = {s.get("language"): root / s.get("path")
            for s in xml.findall("./statements/statement")
            if s.get("type") == "application/pdf"}
    ml_bytes = int(text("memory-limit", str(256 * 1024 * 1024)))
    return {
        "short_name": xml.get("short-name") or root.name,
        "names": names,
        "time_limit_ms": int(text("time-limit", "1000")),
        "memory_limit_mb": max(1, ml_bytes // (1024 * 1024)),
        "input_pattern": text("input-path-pattern", "tests/%02d"),
        "answer_pattern": text("answer-path-pattern", "tests/%02d.a"),
        "tests": tests,
        "groups": groups,
        "checker": source_of("./assets/checker"),
        "interactor": source_of("./assets/interactor"),
        "main": main,
        "executables": executables,
        "validator": validator,
        "pdfs": pdfs,
    }


def read_statements(root: Path, info: dict, dest: Path, slug: str, log: Log = print) -> dict:
    """Convert every language's statement to HTML; copy its images and PDF (if it opens)."""
    out: dict[str, dict] = {}
    base = root / "statements"
    langs = sorted(d.name for d in base.iterdir() if d.is_dir() and not d.name.startswith(".")) \
        if base.exists() else []
    for lang in langs:
        sdir = base / lang
        props_path = sdir / "problem-properties.json"
        if props_path.exists():
            props = json.loads(props_path.read_text(encoding="utf-8"))
        else:
            props = {k: (sdir / f"{k}.tex").read_text(encoding="utf-8")
                     for k in STATEMENT_SECTIONS if (sdir / f"{k}.tex").exists()}
            name_tex = sdir / "name.tex"
            if name_tex.exists():
                props["name"] = name_tex.read_text(encoding="utf-8").strip()
            props["sampleTests"] = []
            for ex in sorted(sdir.glob("example.[0-9][0-9]")):
                ans = ex.with_name(ex.name + ".a")
                props["sampleTests"].append({
                    "input": ex.read_text(encoding="utf-8", errors="replace"),
                    "output": ans.read_text(encoding="utf-8", errors="replace") if ans.exists() else "",
                })
        target = dest / "statements" / lang
        target.mkdir(parents=True, exist_ok=True)
        for f in sdir.iterdir():
            if f.suffix.lower() in IMAGE_EXT:
                shutil.copy2(f, target / f.name)
        pdf = info["pdfs"].get(lang)
        if pdf and pdf.exists():
            shutil.copy2(pdf, target / "problem.pdf")
            shown = pdf.relative_to(root).as_posix() if pdf.is_relative_to(root) else pdf.name
            drop_broken_pdf(target / "problem.pdf", shown, log)

        def img(name: str, _lang=lang) -> str:
            return f"/problem-files/{slug}/{_lang}/{name}"

        entry = {"name": props.get("name") or info["names"].get(lang) or slug,
                 "samples": [{"input": s.get("input", ""), "output": s.get("output", "")}
                             for s in props.get("sampleTests") or []],
                 "pdf": (target / "problem.pdf").exists()}
        for sec in STATEMENT_SECTIONS:
            entry[sec] = latex.to_html(props.get(sec), img)
        out[lang] = entry
    if not out:  # no statement in the package: at least a name and a PDF slot
        for lang, name in info["names"].items():
            out[lang] = {"name": name, "samples": [], "pdf": False,
                         **{s: "" for s in STATEMENT_SECTIONS}}
    return out


def _generate_inputs(root: Path, info: dict, tests_dir: Path, missing: list[dict], log: Log) -> None:
    exe_dir = Path(tempfile.mkdtemp(prefix="gens-"))
    try:
        built: dict[str, Path] = {}
        for src, kind in info["executables"]:
            if languages.from_polygon_type(kind) != "cpp":
                continue
            out = exe_dir / src.stem
            compile_cpp(src, out, [root / "files", src.parent], log)
            built[src.stem] = out
        for t in missing:
            if not t.get("cmd"):
                raise ImportError_(f"test {t['index']} has no input file and no generator command")
            argv = shlex.split(t["cmd"])
            gen = built.get(argv[0])
            if gen is None:
                raise ImportError_(f"test {t['index']}: generator {argv[0]!r} not in the package")
            work = Path(tempfile.mkdtemp(prefix="gen-run-"))
            try:
                with open(tests_dir / f"{t['index']:02d}", "wb") as fout:
                    res = subprocess.run([str(gen), *argv[1:]], cwd=work, stdout=fout,
                                         stderr=subprocess.PIPE, timeout=120)
                if res.returncode != 0:
                    raise ImportError_(f"test {t['index']}: `{t['cmd']}` failed: "
                                       f"{res.stderr.decode(errors='replace')[-500:]}")
                if t.get("from_file"):
                    shutil.copy2(work / t["from_file"], tests_dir / f"{t['index']:02d}")
            finally:
                shutil.rmtree(work, ignore_errors=True)
        log(f"generated {len(missing)} test(s)")
    finally:
        shutil.rmtree(exe_dir, ignore_errors=True)


def _validate(root: Path, info: dict, tests_dir: Path, log: Log) -> None:
    """Run the package's validator over every input, as Polygon does.

    A rejected test is reported, not fatal: the package is the setter's call,
    but a generator that behaves differently here than on Polygon shows up.
    """
    if not info["validator"]:
        return
    src, kind = info["validator"]
    if languages.from_polygon_type(kind) != "cpp":
        log(f"validator is {kind}, not C++: skipped")
        return
    work = Path(tempfile.mkdtemp(prefix="val-"))
    try:
        exe = work / "val"
        compile_cpp(src, exe, [root / "files", src.parent], log)
        bad = []
        for t in info["tests"]:
            argv = [str(exe), "--testset", "tests"]
            if t.get("group"):
                argv += ["--group", str(t["group"])]
            with open(tests_dir / f"{t['index']:02d}", "rb") as fin:
                res = subprocess.run(argv, stdin=fin, capture_output=True, timeout=60, cwd=work)
            if res.returncode != 0:
                bad.append(f"test {t['index']}: {res.stderr.decode(errors='replace').strip()[-300:]}")
        if bad:
            log("WARNING validator rejects:\n  " + "\n  ".join(bad))
        else:
            log(f"validator: all {len(info['tests'])} tests valid")
    finally:
        shutil.rmtree(work, ignore_errors=True)


def keep_source(src: Path, target: Path, root: Path) -> None:
    """Keep a checker's or interactor's source and the package's headers, so a
    contest archive can rebuild the binary on another machine."""
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, target)
    for header in list((root / "files").glob("*.h")) + list(src.parent.glob("*.h")):
        if not (target.parent / header.name).exists():
            shutil.copy2(header, target.parent / header.name)


def rebuild_binaries(problem_dir: Path, log: Log) -> None:
    """Compile check/interactor from src/ (archives carry sources, not binaries)."""
    for name in ("check", "interactor"):
        src = problem_dir / "src" / f"{name}.cpp"
        if src.exists():
            compile_cpp(src, problem_dir / name, [src.parent], log)


def build(root: Path, dest: Path, settings: Settings, log: Log, verify: bool = True) -> dict:
    """Lay the problem out in ``dest`` and return the fields for its DB row."""
    info = parse(root)
    slug = info["short_name"]
    tests_dir = dest / "tests"
    tests_dir.mkdir(parents=True)
    shutil.copy2(root / "problem.xml", dest / "problem.xml")

    # Inputs and answers that ship in the package.
    missing_in, missing_ans = [], []
    for t in info["tests"]:
        i = t["index"]
        src_in = root / (info["input_pattern"] % i)
        src_ans = root / (info["answer_pattern"] % i)
        if src_in.exists():
            shutil.copy2(src_in, tests_dir / f"{i:02d}")
        else:
            missing_in.append(t)
        if src_ans.exists():
            shutil.copy2(src_ans, tests_dir / f"{i:02d}.a")
        else:
            missing_ans.append(i)
    log(f"{len(info['tests'])} tests, {len(missing_in)} to generate, {len(missing_ans)} answers to compute")
    if missing_in:
        _generate_inputs(root, info, tests_dir, missing_in, log)

    _validate(root, info, tests_dir, log)

    checker = "builtin"
    if info["checker"]:
        src, _ = info["checker"]
        compile_cpp(src, dest / "check", [root / "files", src.parent], log)
        keep_source(src, dest / "src" / "check.cpp", root)
        checker = "testlib"
    else:
        log("no checker in the package: using the built-in token comparison")
    interactive = False
    if info["interactor"]:
        src, _ = info["interactor"]
        compile_cpp(src, dest / "interactor", [root / "files", src.parent], log)
        keep_source(src, dest / "src" / "interactor.cpp", root)
        interactive = True

    statements = read_statements(root, info, dest, slug, log)
    tests = [{k: t[k] for k in ("index", "group", "points", "sample")} for t in info["tests"]]
    spec = ProblemSpec(dir=dest, time_limit_ms=info["time_limit_ms"],
                       memory_limit_mb=info["memory_limit_mb"], tests=tests, groups=info["groups"],
                       interactive=interactive, checker=checker)

    main_max_ms = None
    if missing_ans or verify:
        main_max_ms = _run_main(info, spec, missing_ans, settings, log)

    name = (info["names"].get("english") or next(iter(info["names"].values()), None)
            or next(iter(statements.values()), {}).get("name") or slug)
    return {
        "slug": slug, "name": name, "time_limit_ms": info["time_limit_ms"],
        "memory_limit_mb": info["memory_limit_mb"], "interactive": int(interactive),
        "checker": checker, "tests_json": db.dumps(tests), "groups_json": db.dumps(info["groups"]),
        "statements_json": db.dumps(statements), "main_max_ms": main_max_ms,
    }


def _run_main(info: dict, spec: ProblemSpec, missing_ans: list[int], settings: Settings,
              log: Log) -> int | None:
    if not info["main"]:
        if missing_ans:
            raise ImportError_("answers are missing and the package has no main solution")
        log("no main solution in the package: skipping verification")
        return None
    src, kind = info["main"]
    lang_id = languages.from_polygon_type(kind)
    if lang_id is None:
        raise ImportError_(f"main solution type {kind!r} is not supported")
    lang = languages.get(lang_id)
    work = settings.boxes_dir / f"import-{os.getpid()}"
    sandbox = Sandbox(work / "box", uid=settings.sandbox_uid_base + 999,
                      isolate_network=network_isolation_available(),
                      jail=jail_available(settings.boxes_dir),
                      readonly=[settings.pch_dir, settings.runtime_dir],
                      launcher=build_launcher(settings.runtime_dir))
    judge = Judge(sandbox, work / "io", pch_dir=settings.pch_dir)
    try:
        ok, out, run = judge.compile(lang, src.read_text(encoding="utf-8", errors="replace"))
        if not ok:
            raise ImportError_(f"main solution does not compile:\n{out}")
        worst, failures = 0, []
        for t in spec.tests:
            i = t["index"]
            if i in missing_ans:
                r = judge.run_test(spec, lang, run, i, output_to=spec.answer(i))
            else:
                r = judge.run_test(spec, lang, run, i)
            worst = max(worst, r.time_ms)
            if r.verdict != ACCEPTED:
                failures.append(f"test {i}: {r.verdict} {r.message}".strip())
        if missing_ans:
            log(f"computed {len(missing_ans)} answer(s) with the main solution")
        if failures:
            msg = "main solution fails here:\n  " + "\n  ".join(failures[:10])
            if missing_ans:
                raise ImportError_(msg)
            log("WARNING " + msg)
        log(f"main solution: slowest test {worst} ms of a {spec.time_limit_ms} ms limit")
        if worst * 2 > spec.time_limit_ms:
            log("WARNING the main solution uses over half the time limit on this machine — "
                "consider raising the limit")
        return worst
    finally:
        sandbox.clean()
        shutil.rmtree(work, ignore_errors=True)


def import_package(zip_path: Path, settings: Settings, log: Log = print, verify: bool = True) -> int:
    """Import ``zip_path`` (one Polygon package) and return the problem id."""
    ids = import_path(zip_path, settings, log, verify)
    return ids[0]


def import_path(path: Path, settings: Settings, log: Log = print, verify: bool = True) -> list[int]:
    """Import a Polygon package zip, or electicode problems backed up by
    Platform-Scraper (one problem folder, a whole backup, or a zip of either).
    Returns the problem ids."""
    from . import electicode
    settings.ensure_dirs()
    staging = Path(tempfile.mkdtemp(prefix="import-", dir=settings.uploads_dir))
    try:
        if path.is_dir():
            root = path
        else:
            root = staging / "pkg"
            root.mkdir()
            safe_extract(path, root)
        found = electicode.find_problems(root)
        if found:
            ids = []
            for n, folder in enumerate(found):
                built = staging / f"built-{n}"
                ids.append(_save(electicode.build(folder, built, log), built, settings, log))
            return ids
        pkg = find_root(root)
        built = staging / "built"
        return [_save(build(pkg, built, settings, log, verify=verify), built, settings, log)]
    finally:
        shutil.rmtree(staging, ignore_errors=True)


def _save(fields: dict, built_dir: Path, settings: Settings, log: Log) -> int:
    """Move a built problem into place and create or update its row."""
    slug = fields["slug"]
    final = settings.problems_dir / slug
    if final.exists():
        shutil.rmtree(final)
    shutil.move(str(built_dir), final)
    conn = db.connect(settings.db_path)
    try:
        row = db.one(conn, "SELECT id FROM problems WHERE slug=?", (slug,))
        cols = list(fields)
        if row:
            sets = ", ".join(f"{c}=?" for c in cols if c != "slug")
            conn.execute(f"UPDATE problems SET {sets}, status='ready', import_log=? WHERE id=?",
                         [fields[c] for c in cols if c != "slug"] + [_log_text(log), row["id"]])
            pid = row["id"]
        else:
            cur = conn.execute(
                f"INSERT INTO problems ({', '.join(cols)}, status, import_log, created_at) "
                f"VALUES ({', '.join('?' * len(cols))}, 'ready', ?, ?)",
                [fields[c] for c in cols] + [_log_text(log), db.now()])
            pid = cur.lastrowid
    finally:
        conn.close()
    log(f"imported {slug!r} (problem #{pid})")
    return pid


def _log_text(log: Log) -> str:
    return "\n".join(getattr(log, "lines", []))


class Recorder:
    """A log callable that also keeps every line (stored as the import log)."""

    def __init__(self, echo: Callable[[str], None] | None = None):
        self.lines: list[str] = []
        self.echo = echo

    def __call__(self, line: str) -> None:
        self.lines.append(line)
        if self.echo:
            self.echo(line)
